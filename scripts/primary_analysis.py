"""Run the pre-specified primary-survey analysis and write all published outputs.

    python scripts/primary_analysis.py              # uses data/primary/primary_survey_deidentified.csv
    python scripts/primary_analysis.py --raw PATH   # (maintainers) rebuild the de-identified file from the raw export first

Outputs: docs/primary/RESULTS_PRIMARY.md and outputs/primary/*.csv, results.json
"""
import argparse
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from core import primary as P  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--raw", help="path to the raw Google Forms export (contains names; never commit it)")
args = ap.parse_args()
if args.raw:
    assert P.sha256(args.raw) == P.RAW_SHA256, "raw file does not match the registered SHA-256"
    P.deidentify(args.raw).to_csv(P.DEID_PATH, index=False)

df = P.load()
R = P.run_all(df)
OUT = ROOT / "outputs" / "primary"
OUT.mkdir(parents=True, exist_ok=True)


def md(t, floatfmt=".3f"):
    return t.to_markdown(index=False, floatfmt=floatfmt)


R["flow"].to_csv(OUT / "flow.csv", index=False)
R["items"].to_csv(OUT / "item_descriptives.csv", index=False)
R["reliability"].to_csv(OUT / "reliability.csv", index=False)
R["parallel"].to_csv(OUT / "parallel_analysis.csv", index=False)
R["htmt"].to_csv(OUT / "htmt.csv")
R["corr"].to_csv(OUT / "spearman_matrix.csv")
R["hyp"].to_csv(OUT / "hypotheses.csv", index=False)
R["ols"].table.to_csv(OUT / "ols_unique.csv", index=False)
R["ordinal"].to_csv(OUT / "ordinal_logit.csv", index=False)
R["groups"].to_csv(OUT / "users_vs_nonusers.csv", index=False)
R["deck"].to_csv(OUT / "deck_reproduction.csv", index=False)

sens_rows = []
for k, v in R["sensitivity"].items():
    for _, h in v["hyp"].iterrows():
        sens_rows.append({"Sample": k, "n": v["n"], "H": h["H"], "ρ": h["Spearman ρ"], "p (Holm)": h["p (Holm)"],
                          "Decision": h["Decision"]})
    for _, o in v["ols"].table.iterrows():
        sens_rows.append({"Sample": k, "n": v["n"], "H": f"OLS {o['Code']}", "ρ": o["β (std.)"], "p (Holm)": o["p"],
                          "Decision": "β (std.), HC3 p"})
sens = pd.DataFrame(sens_rows)
sens.to_csv(OUT / "sensitivity.csv", index=False)

o = R["ols"]
summary = {
    "raw_sha256": P.RAW_SHA256,
    "n": R["n"],
    "kmo": R["kmo"],
    "harman_first_factor_share": R["harman_share"],
    "components_retained": int(R["parallel"]["Retain"].sum()),
    "reliability": R["reliability"].set_index("Code")[["Inter-item r", "Spearman-Brown", "Cronbach α"]].round(4).to_dict("index"),
    "htmt_max": float(R["htmt"].max().max()),
    "hyp": R["hyp"].set_index("H")[["Spearman ρ", "CI low", "CI high", "p (Holm)", "Decision"]].round(4).to_dict("index"),
    "ols": {"n": o.n, "r2": round(o.r2, 4), "adj_r2": round(o.adj_r2, 4), "f_p": o.f_p,
            "table": o.table.set_index("Code")[["β (std.)", "β CI low", "β CI high", "p", "VIF"]].round(4).to_dict("index")},
    "ordinal": R["ordinal"].set_index("Code")[["Odds ratio", "p"]].round(4).to_dict("index"),
    "q14_q15_spearman": [round(x, 4) for x in R["q14_q15"]],
    "power": {k: round(v, 4) if isinstance(v, float) else v for k, v in R["power"].items()},
    "sensitivity": {k: {"n": v["n"], "hyp": v["hyp"].set_index("H")[["Spearman ρ", "p (Holm)", "Decision"]].round(4).to_dict("index"),
                        "ols_r2": round(v["ols"].r2, 4),
                        "ols": v["ols"].table.set_index("Code")[["β (std.)", "p"]].round(4).to_dict("index")}
                    for k, v in R["sensitivity"].items()},
}
(OUT / "results.json").write_text(json.dumps(summary, indent=2, default=float))

kb = R["kmo"]
lines = [
    "# Primary survey results (genuine responses)",
    "",
    "Generated by `scripts/primary_analysis.py` from `data/primary/primary_survey_deidentified.csv` "
    f"(raw SHA-256 `{P.RAW_SHA256[:16]}…`). Plan: `docs/primary/ANALYSIS_PLAN.md`. Do not edit by hand.",
    "",
    "## 1. Sample flow", md(R["flow"], ".0f"),
    "",
    "## 2. Analytic sample profile (users, n = %d)" % R["n"]["A"],
]
for k, v in R["profile"].items():
    lines.append(f"- {k}: " + ", ".join(f"{i} {n}" for i, n in v.items()))
lines += ["", "Response dates (all 112): " + ", ".join(f"{d} ({n})" for d, n in R["dates"].items()),
          "", "## 3. Item descriptives (sample A)", md(R["items"].drop(columns=["Statement"]), ".2f"),
          "", "## 4. Reliability (two-item scales)", md(R["reliability"]),
          "", f"## 5. Factorability and dimensionality\n- KMO = {kb['KMO']:.3f}; Bartlett χ² = {kb['Bartlett chi2']:.1f}, df = {kb['df']}, p = {kb['p']:.2e}",
          f"- Components retained by parallel analysis: {int(R['parallel']['Retain'].sum())}; first-component share of variance (Harman diagnostic) = {R['harman_share']:.1%}",
          "", md(R["parallel"], ".3f"),
          "", "## 6. Discriminant validity (HTMT)", R["htmt"].round(3).to_markdown(),
          "", "## 7. Spearman correlations of construct scores (sample A)", R["corr"].round(3).to_markdown(),
          "", "## 8. Hypothesis tests H1–H4 (primary: Spearman ρ with TBCI, one-sided, Holm-adjusted)", md(R["hyp"].drop(columns=["Code"])),
          "", f"## 9. Unique association: OLS TBCI ~ TRN + CON + GOV + COM (HC3), n = {o.n}, R² = {o.r2:.3f}, adj. R² = {o.adj_r2:.3f}, F-test p = {o.f_p:.2e}",
          md(o.table), "", "## 10. Robustness: ordinal logistic regression", md(R["ordinal"]),
          "", f"## 11. H5 and mediation\nNot tested: the form contains no separate measure of trust and of usage intention. Q14–Q15 Spearman ρ = {R['q14_q15'][0]:.3f} "
              f"[{R['q14_q15'][1]:.3f}, {R['q14_q15'][2]:.3f}] (descriptive only).",
          "", "## 12. Exploratory: users vs non-users (Mann-Whitney)", md(R["groups"]),
          "", "## 13. Power (n = %d, α = .05, power .80)" % R["n"]["A"],
          f"- Smallest detectable f² for the 4-predictor model: {R['power']['min f2 (4-predictor model)']:.3f} (R² ≈ {R['power']['min R2 equivalent']:.3f})",
          f"- Smallest detectable f² for one predictor's unique contribution: {R['power']['min f2 (single predictor, unique)']:.3f}",
          "", "## 14. Sensitivity analyses", md(sens),
          "", "## 15. Reproduction of the statistics in the team's final deck",
          "All 112 rows, only the four numerically exported items (Q10, Q12, Q14, Q15). Shows where the deck's numbers came from; "
          "it is not part of the hypothesis tests.", md(R["deck"]), ""]
(ROOT / "docs" / "primary" / "RESULTS_PRIMARY.md").write_text("\n".join(lines))
print("ok", R["n"])
